package domain

import "strings"

// ChapterPlan is the chapter writing concept, generated autonomously by the Writer.
// Scene splitting is no longer enforced; the Agent decides for itself how to organize the content.
type ChapterPlan struct {
	Chapter    int             `json:"chapter"`
	Title      string          `json:"title"`
	Goal       string          `json:"goal"`
	Conflict   string          `json:"conflict"`
	Hook       string          `json:"hook"`
	EmotionArc string          `json:"emotion_arc,omitempty"`
	Notes      string          `json:"notes,omitempty"` // The Agent's free-form notes
	Contract   ChapterContract `json:"contract,omitempty"`
}

// ChapterContract is the chapter acceptance contract shared by the Writer and the Editor.
// It defines the progress items this chapter must complete, the out-of-bounds items it must avoid, and the review focus points.
type ChapterContract struct {
	RequiredBeats    []string `json:"required_beats,omitempty"`    // Progress items that must land in this chapter
	ForbiddenMoves   []string `json:"forbidden_moves,omitempty"`   // Progress that explicitly must not happen in this chapter
	ContinuityChecks []string `json:"continuity_checks,omitempty"` // Continuity points that need special checking in this chapter
	EvaluationFocus  []string `json:"evaluation_focus,omitempty"`  // Points the Editor needs to check with priority
	EmotionTarget    string   `json:"emotion_target,omitempty"`    // Optional: the emotion the reader is mainly meant to feel in this chapter
	PayoffPoints     []string `json:"payoff_points,omitempty"`     // Optional: the plot point / payoff a key chapter is meant to respond to
	HookGoal         string   `json:"hook_goal,omitempty"`         // Optional: the urge to keep reading that the chapter-ending hook is meant to drive
}

// ChapterSummary is a chapter summary, used in the context window of later chapters.
type ChapterSummary struct {
	Chapter    int      `json:"chapter"`
	Title      string   `json:"title"`
	Summary    string   `json:"summary"`
	Characters []string `json:"characters"`
	KeyEvents  []string `json:"key_events"`
}

// ArcSummary is an arc-level summary, generated by the Editor when the arc ends.
type ArcSummary struct {
	Volume    int      `json:"volume"`
	Arc       int      `json:"arc"`
	Title     string   `json:"title"`
	Summary   string   `json:"summary"`
	KeyEvents []string `json:"key_events"`
}

// VolumeSummary is a volume-level summary, generated when the volume ends.
type VolumeSummary struct {
	Volume    int      `json:"volume"`
	Title     string   `json:"title"`
	Summary   string   `json:"summary"`
	KeyEvents []string `json:"key_events"`
}

// CharacterSnapshot is a snapshot of character state, recorded at arc boundaries.
type CharacterSnapshot struct {
	Volume     int    `json:"volume"`
	Arc        int    `json:"arc"`
	Name       string `json:"name"`
	Status     string `json:"status"`
	Power      string `json:"power,omitempty"`
	Motivation string `json:"motivation"`
	Relations  string `json:"relations,omitempty"`
}

// OutlineFeedback is the Writer's feedback on the outline, optional when committing a chapter.
type OutlineFeedback struct {
	Deviation  string `json:"deviation"`  // Description of the deviation
	Suggestion string `json:"suggestion"` // Adjustment suggestion
}

// WritingStyleRules are the writing rules distilled from the chapters already written, generated by the Editor at arc boundaries.
// They replace excerpts of the original text (style_anchors / voice_samples), using rules instead of copying the original text.
type WritingStyleRules struct {
	Volume    int              `json:"volume"`
	Arc       int              `json:"arc"`
	Prose     []string         `json:"prose"`      // 3-5 narrative style rules, each ≤50 characters
	Dialogue  []CharacterVoice `json:"dialogue"`   // Character dialogue style rules
	Taboos    []string         `json:"taboos"`     // Taboo list
	UpdatedAt string           `json:"updated_at"` // ISO8601 timestamp
}

// CharacterVoice is the dialogue style rules of a single character.
type CharacterVoice struct {
	Name  string   `json:"name"`
	Rules []string `json:"rules"` // 2-3 language-trait rules, each ≤30 characters
}

// RelatedChapter is a related chapter recommended for re-reading.
type RelatedChapter struct {
	Chapter int    `json:"chapter"`
	Reason  string `json:"reason"`
}

// RecallItem is long-term information recalled selectively for the current task.
// It does not replace formal artifacts; it only injects back into the model the small amount of history that is truly relevant to the current round.
type RecallItem struct {
	Kind    string `json:"kind"`
	Key     string `json:"key,omitempty"`
	Chapter int    `json:"chapter,omitempty"`
	Reason  string `json:"reason,omitempty"`
	Summary string `json:"summary,omitempty"`
}

// CommitResult is the structured return value of the commit_chapter tool.
// It contains only fact fields; "what to do next" is generated by the Reminder channel on its own, based on the current Progress.
type CommitResult struct {
	Chapter        int              `json:"chapter"`
	Committed      bool             `json:"committed"`
	WordCount      int              `json:"word_count"`
	NextChapter    int              `json:"next_chapter"`
	ReviewRequired bool             `json:"review_required"`
	ReviewReason   string           `json:"review_reason,omitempty"`
	HookType       string           `json:"hook_type,omitempty"`
	DominantStrand string           `json:"dominant_strand,omitempty"`
	Feedback       *OutlineFeedback `json:"feedback,omitempty"`
	// Long-form layered signals
	ArcEnd         bool `json:"arc_end,omitempty"`
	VolumeEnd      bool `json:"volume_end,omitempty"`
	Volume         int  `json:"volume,omitempty"`
	Arc            int  `json:"arc,omitempty"`
	NeedsExpansion bool `json:"needs_expansion,omitempty"`  // The next arc is a skeleton and its chapters need to be expanded
	NeedsNewVolume bool `json:"needs_new_volume,omitempty"` // The Architect needs to create the next volume
	NextVolume     int  `json:"next_volume,omitempty"`      // Next arc / volume number
	NextArc        int  `json:"next_arc,omitempty"`         // Next arc number
	// Completion-state fact: whether the whole book is complete after this commit
	BookComplete bool `json:"book_complete,omitempty"`
	// Current Progress.Flow snapshot (writing / reviewing / rewriting / polishing)
	Flow string `json:"flow,omitempty"`
}

// HasDirective decides whether this chapter plan really makes clear "what it should be written to look like".
//
// An empty plan is equivalent to no plan: during rework, listing only defects without giving direction leaves the Writer with just the
// single sentence "rewrite chapter N" - the Editor was observed judging this as the most serious issue in the queue.
func (p ChapterPlan) HasDirective() bool {
	return strings.TrimSpace(p.Goal) != "" ||
		len(p.Contract.RequiredBeats) > 0 ||
		len(p.Contract.PayoffPoints) > 0 ||
		len(p.Contract.ContinuityChecks) > 0
}
